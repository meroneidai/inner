    /**
     * @param  array<string, Article>  $saved
     * @param  array<string, list<string>>  $map
     */
    private function syncRelated(array $saved, array $map): void
    {
        foreach ($map as $slug => $relatedSlugs) {
            if (! isset($saved[$slug])) {
                continue;
            }

            $sync = [];
            foreach ($relatedSlugs as $order => $relatedSlug) {
                if (isset($saved[$relatedSlug])) {
                    $sync[$saved[$relatedSlug]->id] = ['sort_order' => $order + 1];
                }
            }

            $saved[$slug]->relatedArticles()->sync($sync);
        }
    }
